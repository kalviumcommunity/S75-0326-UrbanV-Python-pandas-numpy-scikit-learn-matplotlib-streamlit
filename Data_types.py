# Numeric data types
a = 10
b = 3.5

print("Addition:", a + b)
print("Division:", a / b)

# String data types
name = "Paul"
greeting = "Hello " + name
print(greeting)

# Mixing types (will cause error if not handled)
age = 20
print("Age: " + str(age))  # convert number to string

# Type checking
print(type(a))
print(type(b))
print(type(name))